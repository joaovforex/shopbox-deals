// Ative para colocar a loja em modo manutenção (link inacessível ao público).
const MAINTENANCE_MODE = false;

function MaintenanceScreen() {
  return (
    <div className="min-h-screen flex flex-col items-center justify-center bg-background px-6 text-center">
      <div className="max-w-md space-y-4">
        <h1 className="text-4xl font-bold text-foreground">Loja temporariamente indisponível</h1>
        <p className="text-muted-foreground">
          Estamos em manutenção. Voltaremos em breve. Obrigado pela compreensão.
        </p>
      </div>
    </div>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const [themeMode, setThemeMode] = useState<"light" | "dark">("light");

  useEffect(() => {
    const sync = () =>
      setThemeMode(document.documentElement.classList.contains("dark") ? "dark" : "light");
    sync();
    const obs = new MutationObserver(sync);
    obs.observe(document.documentElement, { attributes: true, attributeFilter: ["class"] });
    return () => obs.disconnect();
  }, []);

  if (MAINTENANCE_MODE) {
    return <MaintenanceScreen />;
  }

  return (
    <QueryClientProvider client={queryClient}>
      <CartProvider>
        {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
        <Outlet />
        <Toaster richColors position="top-center" theme={themeMode} />
        <FloatingActions />
      </CartProvider>
    </QueryClientProvider>
  );
}
